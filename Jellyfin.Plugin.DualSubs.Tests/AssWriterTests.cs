using Jellyfin.Plugin.DualSubs.Core;

namespace Jellyfin.Plugin.DualSubs.Tests;

public class AssWriterTests
{
    [Fact]
    public void GoldenDocumentIsStable()
    {
        var primary = new List<Cue>
        {
            new(TimeSpan.FromMilliseconds(1500), TimeSpan.FromMilliseconds(3200), "Hello there."),
            new(TimeSpan.FromSeconds(65.999), TimeSpan.FromSeconds(68), "Second line\nwith {braces}")
        };
        var secondary = new List<Cue>
        {
            new(TimeSpan.FromMilliseconds(1400), TimeSpan.FromMilliseconds(3100), "Hola."),
            new(TimeSpan.FromSeconds(65.5), TimeSpan.FromSeconds(67.8), "Segunda {línea}")
        };

        var actual = AssWriter.Write(primary, secondary, new DualSubsStyleOptions(), "eng+spa", "abc123");

        var expected = File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "TestData", "golden.ass"));
        Assert.Equal(expected, actual);
    }

    [Fact]
    public void WritesOwnershipMetadataAndOffset()
    {
        var ass = AssWriter.Write([], [], new DualSubsStyleOptions(), "eng+spa", "deadbeef", -2300);

        Assert.Contains("; Generated by Jellyfin DualSubs", ass);
        Assert.Contains("; DualSubs-Version: 1", ass);
        Assert.Contains("; DualSubs-Pair: eng+spa", ass);
        Assert.Contains("; DualSubs-SourceHash: deadbeef", ass);
        Assert.Contains("; DualSubs-OffsetMs: -2300", ass);
        Assert.Contains("Title: Dual ENG/SPA", ass);
    }

    [Fact]
    public void EscapesNewlinesAndBracesButKeepsBackslashes()
    {
        Assert.Equal(@"one\Ntwo (tag) \N", AssWriter.EscapeText("one\ntwo {tag} \\N"));
        Assert.Equal("a\r\nb", AssWriter.EscapeText("a\r\nb").Replace(@"\N", "\r\n", StringComparison.Ordinal));
    }

    [Theory]
    [InlineData(0, 0, 0, 0, "0:00:00.00")]
    [InlineData(1, 2, 3, 456, "1:02:03.45")]
    [InlineData(9, 59, 59, 999, "9:59:59.99")]
    [InlineData(10, 0, 0, 0, "10:00:00.00")]
    [InlineData(100, 1, 1, 1, "100:01:01.00")]
    public void FormatsTimeWithCentisecondsTruncated(int hours, int minutes, int seconds, int milliseconds, string expected)
    {
        var time = new TimeSpan(0, hours, minutes, seconds, milliseconds);

        Assert.Equal(expected, AssWriter.FormatTime(time));
    }

    [Fact]
    public void TopBottomLayoutUsesTopAndBottomAlignments()
    {
        var ass = AssWriter.Write([], [], new DualSubsStyleOptions { Layout = "TopBottom" }, "eng+spa", "hash");

        Assert.Contains("Style: Primary,Arial,62,&H00FFFFFF", ass);
        Assert.Contains(",1,3,1,2,60,60,50,1", ass);
        Assert.Contains("Style: Secondary,Arial,50,&H0080E6FF", ass);
        Assert.Contains(",1,3,1,8,60,60,40,1", ass);
    }

    [Fact]
    public void StackedBottomPutsSecondaryAbovePrimary()
    {
        var ass = AssWriter.Write(
            [],
            [],
            new DualSubsStyleOptions { Layout = "StackedBottom", PrimaryFontSize = 50 },
            "eng+spa",
            "hash");

        Assert.Contains(",1,3,1,2,60,60,50,1", ass);
        Assert.Contains(",1,3,1,2,60,60,170,1", ass);
    }

    [Fact]
    public void InterleavesEventsByStartTime()
    {
        var ass = AssWriter.Write(
            [new Cue(TimeSpan.FromSeconds(2), TimeSpan.FromSeconds(3), "P")],
            [new Cue(TimeSpan.FromSeconds(1), TimeSpan.FromSeconds(2), "S")],
            new DualSubsStyleOptions(),
            "eng+spa",
            "hash");

        Assert.True(ass.IndexOf(",Secondary", StringComparison.Ordinal) < ass.IndexOf(",Primary", StringComparison.Ordinal));
    }

    [Fact]
    public void AppliesItalicToSecondaryOnly()
    {
        var ass = AssWriter.Write([], [], new DualSubsStyleOptions { SecondaryItalic = true }, "eng+spa", "hash");

        Assert.Contains("Style: Secondary,Arial,50,&H0080E6FF,&H000000FF,&H00000000,&H64000000,0,1,0,0", ass);
    }
}
