using MediaBrowser.Model.Entities;

namespace Jellyfin.Plugin.DualSubs.Services;

/// <summary>
/// Chooses source subtitle tracks according to the plugin rules.
/// </summary>
public static class SourceTrackSelector
{
    /// <summary>
    /// Returns usable text tracks for a language, best first.
    /// </summary>
    /// <param name="streams">Media streams of the primary media source.</param>
    /// <param name="normalizedLanguage">Normalized ISO 639-2 language.</param>
    /// <param name="normalize">Language normalizer.</param>
    /// <param name="isPluginFile">Returns true for files generated by this plugin.</param>
    /// <returns>Ordered candidates.</returns>
    public static IReadOnlyList<MediaStream> SelectCandidates(
        IEnumerable<MediaStream> streams,
        string normalizedLanguage,
        Func<string?, string> normalize,
        Func<MediaStream, bool>? isPluginFile = null)
    {
        ArgumentNullException.ThrowIfNull(streams);
        ArgumentNullException.ThrowIfNull(normalize);

        return streams
            .Where(stream => stream.Type == MediaStreamType.Subtitle)
            .Where(stream => stream.IsTextSubtitleStream)
            .Where(stream => !stream.IsForced)
            .Where(stream => !string.IsNullOrWhiteSpace(stream.Language))
            .Where(stream => string.Equals(normalize(stream.Language), normalizedLanguage, StringComparison.OrdinalIgnoreCase))
            .Where(stream => isPluginFile is null || !isPluginFile(stream))
            .OrderBy(stream => stream.IsHearingImpaired)
            .ThenByDescending(stream => stream.IsExternal)
            .ThenBy(stream => stream.Index)
            .ToList();
    }

    /// <summary>
    /// Picks the candidate with the most cues after applying the priority tiers.
    /// </summary>
    /// <param name="candidates">Candidates with their parsed cue counts.</param>
    /// <returns>The chosen stream, or null.</returns>
    public static MediaStream? ChooseBest(IReadOnlyList<(MediaStream Stream, int CueCount)> candidates)
    {
        ArgumentNullException.ThrowIfNull(candidates);

        var usable = candidates.Where(item => item.CueCount > 0).ToList();
        if (usable.Count == 0)
        {
            return null;
        }

        var nonSdh = usable.Where(item => !item.Stream.IsHearingImpaired).ToList();
        if (nonSdh.Count > 0)
        {
            usable = nonSdh;
        }

        var external = usable.Where(item => item.Stream.IsExternal).ToList();
        if (external.Count > 0)
        {
            usable = external;
        }

        return usable
            .OrderByDescending(item => item.CueCount)
            .ThenBy(item => item.Stream.Index)
            .First()
            .Stream;
    }

    /// <summary>
    /// Returns true when the language only has bitmap or forced subtitle tracks.
    /// </summary>
    /// <param name="streams">Media streams.</param>
    /// <param name="normalizedLanguage">Normalized language.</param>
    /// <param name="normalize">Language normalizer.</param>
    /// <returns>True for bitmap-only languages.</returns>
    public static bool HasBitmapOnlyForLanguage(
        IEnumerable<MediaStream> streams,
        string normalizedLanguage,
        Func<string?, string> normalize)
    {
        ArgumentNullException.ThrowIfNull(streams);
        ArgumentNullException.ThrowIfNull(normalize);

        var tracks = streams
            .Where(stream => stream.Type == MediaStreamType.Subtitle)
            .Where(stream => !stream.IsForced)
            .Where(stream => !string.IsNullOrWhiteSpace(stream.Language))
            .Where(stream => string.Equals(normalize(stream.Language), normalizedLanguage, StringComparison.OrdinalIgnoreCase))
            .ToList();

        return tracks.Count > 0 && tracks.All(stream => !stream.IsTextSubtitleStream);
    }
}
