using System.Net.Mime;
using Jellyfin.Plugin.DualSubs.Api;
using Jellyfin.Plugin.DualSubs.Services;
using MediaBrowser.Common.Api;
using MediaBrowser.Controller.Entities;
using MediaBrowser.Controller.Library;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;

namespace Jellyfin.Plugin.DualSubs.Api;

/// <summary>
/// Dual subtitles REST API.
/// </summary>
[ApiController]
[Authorize]
[Route("DualSubs")]
[Produces(MediaTypeNames.Application.Json)]
public sealed class DualSubsController : ControllerBase
{
    private readonly ILibraryManager _libraryManager;
    private readonly DualSubtitleService _service;

    /// <summary>
    /// Initializes a new instance of the <see cref="DualSubsController"/> class.
    /// </summary>
    /// <param name="libraryManager">Library manager.</param>
    /// <param name="service">Dual subtitle service.</param>
    public DualSubsController(ILibraryManager libraryManager, DualSubtitleService service)
    {
        _libraryManager = libraryManager;
        _service = service;
    }

    /// <summary>
    /// Generates or regenerates every enabled pair for one item.
    /// </summary>
    /// <param name="itemId">Item id.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>Result per pair.</returns>
    [HttpPost("Items/{itemId:guid}/Generate")]
    [Authorize(Policy = Policies.RequiresElevation)]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<ActionResult<DualSubsGenerateResponse>> Generate(
        [FromRoute] Guid itemId,
        CancellationToken cancellationToken)
    {
        var video = _libraryManager.GetItemById<Video>(itemId);
        if (video is null)
        {
            return NotFound();
        }

        return Ok(await _service.GenerateAsync(video, cancellationToken).ConfigureAwait(false));
    }

    /// <summary>
    /// Deletes only the files generated by this plugin for one item.
    /// </summary>
    /// <param name="itemId">Item id.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>Number of removed files.</returns>
    [HttpDelete("Items/{itemId:guid}")]
    [Authorize(Policy = Policies.RequiresElevation)]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<ActionResult<DualSubsDeleteResponse>> Delete(
        [FromRoute] Guid itemId,
        CancellationToken cancellationToken)
    {
        var video = _libraryManager.GetItemById<Video>(itemId);
        if (video is null)
        {
            return NotFound();
        }

        var deleted = await _service.DeleteAllGeneratedAsync(video, cancellationToken).ConfigureAwait(false);
        return Ok(new DualSubsDeleteResponse(video.Id, deleted));
    }

    /// <summary>
    /// Shows which source tracks would be used and the estimated offset, without writing.
    /// </summary>
    /// <param name="itemId">Item id.</param>
    /// <param name="pair">Pair such as eng+spa.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>Preview.</returns>
    [HttpGet("Items/{itemId:guid}/Preview")]
    [Authorize(Policy = Policies.RequiresElevation)]
    [ProducesResponseType(StatusCodes.Status200OK)]
    [ProducesResponseType(StatusCodes.Status400BadRequest)]
    [ProducesResponseType(StatusCodes.Status404NotFound)]
    public async Task<ActionResult<DualSubsPreviewResponse>> Preview(
        [FromRoute] Guid itemId,
        [FromQuery] string pair,
        CancellationToken cancellationToken)
    {
        var video = _libraryManager.GetItemById<Video>(itemId);
        if (video is null)
        {
            return NotFound();
        }

        if (string.IsNullOrWhiteSpace(pair))
        {
            return BadRequest(new { message = "The pair query parameter is required, for example eng+spa." });
        }

        return Ok(await _service.PreviewAsync(video, pair, cancellationToken).ConfigureAwait(false));
    }
}
