using System.Globalization;
using System.Text;

namespace Jellyfin.Plugin.DualSubs.Core;

/// <summary>
/// Builds an ASS document from two cue tracks.
/// </summary>
public static class AssWriter
{
    /// <summary>
    /// Writes the ASS document. The caller is responsible for UTF-8 BOM encoding.
    /// </summary>
    /// <param name="primaryCues">Primary language cues (bottom).</param>
    /// <param name="secondaryCues">Secondary language cues (top or stacked).</param>
    /// <param name="options">Style options.</param>
    /// <param name="pair">Normalized language pair, for example eng+spa.</param>
    /// <param name="sourceHash">Source hash written as metadata.</param>
    /// <param name="offsetMs">Applied offset, written as metadata.</param>
    /// <returns>ASS text.</returns>
    public static string Write(
        IReadOnlyList<Cue> primaryCues,
        IReadOnlyList<Cue> secondaryCues,
        DualSubsStyleOptions options,
        string pair,
        string sourceHash,
        int offsetMs = 0)
    {
        ArgumentNullException.ThrowIfNull(primaryCues);
        ArgumentNullException.ThrowIfNull(secondaryCues);
        ArgumentNullException.ThrowIfNull(options);
        ArgumentException.ThrowIfNullOrWhiteSpace(pair);
        ArgumentNullException.ThrowIfNull(sourceHash);

        var stacked = string.Equals(options.Layout, "StackedBottom", StringComparison.OrdinalIgnoreCase);
        var secondaryAlignment = stacked ? 2 : 8;
        var secondaryMargin = stacked
            ? options.PrimaryMarginV + (int)Math.Round(options.PrimaryFontSize * 2.4, MidpointRounding.AwayFromZero)
            : options.SecondaryMarginV;

        var builder = new StringBuilder();
        builder.AppendLine("[Script Info]");
        builder.AppendLine("; Generated by Jellyfin DualSubs");
        builder.AppendLine("; DualSubs-Version: 1");
        builder.Append("; DualSubs-Pair: ").AppendLine(pair);
        builder.Append("; DualSubs-SourceHash: ").AppendLine(sourceHash);
        builder.Append("; DualSubs-OffsetMs: ").AppendLine(offsetMs.ToString(CultureInfo.InvariantCulture));
        builder.Append("Title: Dual ").AppendLine(pair.Replace('+', '/').ToUpperInvariant());
        builder.AppendLine("ScriptType: v4.00+");
        builder.AppendLine("PlayResX: 1920");
        builder.AppendLine("PlayResY: 1080");
        builder.AppendLine("ScaledBorderAndShadow: yes");
        builder.AppendLine("WrapStyle: 0");
        builder.AppendLine();
        builder.AppendLine("[V4+ Styles]");
        builder.AppendLine("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding");
        builder.Append("Style: Primary,Arial,")
            .Append(options.PrimaryFontSize.ToString(CultureInfo.InvariantCulture))
            .Append(',').Append(AssColor.FromHtml(options.PrimaryColor))
            .Append(",&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,")
            .Append(options.OutlineSize.ToString(CultureInfo.InvariantCulture))
            .Append(",1,2,60,60,")
            .Append(options.PrimaryMarginV.ToString(CultureInfo.InvariantCulture))
            .AppendLine(",1");
        builder.Append("Style: Secondary,Arial,")
            .Append(options.SecondaryFontSize.ToString(CultureInfo.InvariantCulture))
            .Append(',').Append(AssColor.FromHtml(options.SecondaryColor))
            .Append(",&H000000FF,&H00000000,&H64000000,0,")
            .Append(options.SecondaryItalic ? '1' : '0')
            .Append(",0,0,100,100,0,0,1,")
            .Append(options.OutlineSize.ToString(CultureInfo.InvariantCulture))
            .Append(",1,")
            .Append(secondaryAlignment.ToString(CultureInfo.InvariantCulture))
            .Append(",60,60,")
            .Append(secondaryMargin.ToString(CultureInfo.InvariantCulture))
            .AppendLine(",1");
        builder.AppendLine();
        builder.AppendLine("[Events]");
        builder.AppendLine("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text");

        var events = primaryCues.Select(cue => (Cue: cue, Style: "Primary"))
            .Concat(secondaryCues.Select(cue => (Cue: cue, Style: "Secondary")))
            .OrderBy(item => item.Cue.Start);

        foreach (var item in events)
        {
            builder.Append("Dialogue: 0,")
                .Append(FormatTime(item.Cue.Start))
                .Append(',')
                .Append(FormatTime(item.Cue.End))
                .Append(',')
                .Append(item.Style)
                .Append(",,0,0,0,,")
                .AppendLine(EscapeText(item.Cue.Text));
        }

        return builder.ToString();
    }

    /// <summary>
    /// Formats a time as <c>H:MM:SS.cc</c>, truncating milliseconds to centiseconds.
    /// </summary>
    /// <param name="time">Time to format.</param>
    /// <returns>ASS timestamp.</returns>
    public static string FormatTime(TimeSpan time)
    {
        if (time < TimeSpan.Zero)
        {
            time = TimeSpan.Zero;
        }

        var totalCentiseconds = (long)(time.TotalMilliseconds / 10);
        var hours = totalCentiseconds / 360_000;
        var minutes = totalCentiseconds / 6_000 % 60;
        var seconds = totalCentiseconds / 100 % 60;
        var centiseconds = totalCentiseconds % 100;

        return string.Create(
            CultureInfo.InvariantCulture,
            $"{hours}:{minutes:00}:{seconds:00}.{centiseconds:00}");
    }

    /// <summary>
    /// Escapes text for an ASS Dialogue line.
    /// </summary>
    /// <param name="text">Text to escape.</param>
    /// <returns>Escaped text.</returns>
    public static string EscapeText(string text)
    {
        return (text ?? string.Empty)
            .Replace("\r\n", "\n", StringComparison.Ordinal)
            .Replace('\r', '\n')
            .Replace("\n", "\\N", StringComparison.Ordinal)
            .Replace("{", "(", StringComparison.Ordinal)
            .Replace("}", ")", StringComparison.Ordinal);
    }
}
